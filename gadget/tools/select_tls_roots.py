#!/usr/bin/env python3
"""Select existing trusted CA roots per provider to reduce TLS heap usage.

Sources remain the public system-store certificates in include/tls_roots.h.
Run again after refreshing that source file; never disable certificate checks.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'include/tls_roots.h').read_text()
certificates = dict(re.findall(r'// ([^\n]+)\n(-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----)', source))
providers = {
    'OPENAI_TLS_ROOTS': ['GTS Root R4'],
    'GOOGLE_TLS_ROOTS': ['GTS Root R1', 'GTS Root R4'],
    'WEATHER_TLS_ROOTS': ['GTS Root R4', 'ISRG Root X1', 'ISRG Root X2'],
}
output = '// Generated by tools/select_tls_roots.py from existing public CA roots.\n#pragma once\n\n'
for name, roots in providers.items():
    pem = '\n'.join(certificates[root] for root in roots)
    output += f'static const char {name}[] = R"PEM(\n{pem}\n)PEM";\n\n'
(ROOT / 'include/tls_providers.h').write_text(output)
print('Provider-specific CA roots generated; certificate validation remains required.')
