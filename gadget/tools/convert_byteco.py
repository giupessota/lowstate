#!/usr/bin/env python3
"""Convert Byteco's reference-derived asset to LVGL 8 RGB565 plus alpha.

Run with `uv run --with pillow python gadget/tools/convert_byteco.py`.
The menu face is cropped independently so transparent sprite padding cannot
cut off the chin or shrink the face inside its icon.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
original = Image.open(ROOT / 'assets/byteco.png').convert('RGBA')
image = original.crop(original.getbbox())
image.thumbnail((48, 64), Image.Resampling.LANCZOS)
sprite = Image.new('RGBA', (48, 64))
sprite.alpha_composite(image, ((48 - image.width) // 2, 64 - image.height))
sprite.save(ROOT / 'assets/byteco-small.png')
# This asset's complete head, including ear discs and chin, excludes the body.
face = original.crop((220, 55, 990, 630))
face.thumbnail((28, 24), Image.Resampling.LANCZOS)
icon = Image.new('RGBA', (28, 24))
icon.alpha_composite(face, ((28 - face.width) // 2, (24 - face.height) // 2))
icon.save(ROOT / 'assets/byteco-icon.png')


def source_for(image, name):
    """Encode an RGBA image as a flash-resident LVGL image descriptor."""
    data = []
    for r, g, b, a in image.get_flattened_data():
        rgb565 = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend((rgb565 & 255, rgb565 >> 8, a))
    rows = [', '.join(f'0x{value:02x}' for value in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f'''static const uint8_t {name}_pixels[] = {{
''' + ',\n'.join(rows) + f'''
}};
const lv_img_dsc_t {name} = {{
  .header = {{ .cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .always_zero = 0, .reserved = 0, .w = {image.width}, .h = {image.height} }},
  .data_size = sizeof({name}_pixels),
  .data = {name}_pixels,
}};
'''

source = '// Generated by tools/convert_byteco.py; RGB565 little-endian + alpha.\n#include "byteco_sprite.h"\n\n'
portrait = original.crop((170, 55, 1000, 1260))
portrait.thumbnail((112, 164), Image.Resampling.LANCZOS)
portrait.save(ROOT / 'assets/byteco-portrait.png')
source += source_for(sprite, 'byteco_sprite') + '\n' + source_for(icon, 'byteco_icon')
# Indexed RGBA preserves transparency while reducing the large portrait in flash.
indexed = portrait.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
palette = indexed.getpalette('RGBA')
encoded = []
for i in range(0, 1024, 4):
    r, g, b, a = palette[i:i + 4]
    encoded.extend((b, g, r, a))
encoded.extend(indexed.tobytes())
rows = [', '.join(f'0x{value:02x}' for value in encoded[i:i + 24]) for i in range(0, len(encoded), 24)]
source += '\nstatic const uint8_t portrait_indexed[] = {\n' + ',\n'.join(rows) + '\n};\n'
source += f'''const lv_img_dsc_t byteco_portrait = {{
  .header = {{ .cf = LV_IMG_CF_INDEXED_8BIT, .always_zero = 0, .reserved = 0, .w = {portrait.width}, .h = {portrait.height} }},
  .data_size = sizeof(portrait_indexed), .data = portrait_indexed,
}};
'''

(ROOT / 'src/byteco_sprite.cpp').write_text(source)
print('Byteco: full 48 x 64 sprite and complete 28 x 24 face icon')
