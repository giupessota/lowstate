#!/usr/bin/env node
'use strict';
// Share the exact same personality between the optional bridge and firmware.
const fs = require('node:fs');
const path = require('node:path');
const { INSTRUCTIONS, MODES } = require('./byteco-server.cjs');
const source = '// Generated by node scripts/byteco-prompts.cjs. No secrets.\n#pragma once\n\n'
  + 'namespace byteco {\nstatic const char* const PROMPTS[] = {\n'
  + Object.values(MODES).map(mode => `  ${JSON.stringify(`${INSTRUCTIONS}\n${mode}`)},`).join('\n')
  + '\n};\n}\n';
fs.writeFileSync(path.join(__dirname, '../gadget/src/byteco_prompts.h'), source);
console.log('Byteco firmware prompts updated.');
